"""## Combining All Activations Into One Unified Model

To see what happens when we use all four activations together, we will build a parallel multi-activation layer model where different sub-paths of the network utilize different activations (**ReLU**, **Tanh**, **Sin**, and **SwiGLU**) simultaneously. Their representations are then concatenated and fed to a final classification layer.
"""

class UnifiedMultiActivationModel(nn.Module):
    def __init__(self, input_dim=2, sub_hidden_dim=30):
        super().__init__()
        # Separate processing branches for each activation type
        self.relu_branch = nn.Sequential(
            nn.Linear(input_dim, sub_hidden_dim),
            nn.ReLU(),
            nn.Linear(sub_hidden_dim, sub_hidden_dim),
            nn.ReLU()
        )

        self.tanh_branch = nn.Sequential(
            nn.Linear(input_dim, sub_hidden_dim),
            nn.Tanh(),
            nn.Linear(sub_hidden_dim, sub_hidden_dim),
            nn.Tanh()
        )

        self.sin_branch = nn.Sequential(
            nn.Linear(input_dim, sub_hidden_dim),
            SinActivation(),
            nn.Linear(sub_hidden_dim, sub_hidden_dim),
            SinActivation()
        )

        # SwiGLU inherently handles its own projections
        self.swiglu_branch = nn.Sequential(
            SwiGLUActivation(input_dim, sub_hidden_dim),
            SwiGLUActivation(sub_hidden_dim, sub_hidden_dim)
        )

        # Concatenate features from all 4 branches (4 * sub_hidden_dim)
        combined_dim = sub_hidden_dim * 4
        self.classifier = nn.Linear(combined_dim, 1)

    def forward(self, x):
        feat_relu = self.relu_branch(x)
        feat_tanh = self.tanh_branch(x)
        feat_sin = self.sin_branch(x)
        feat_swiglu = self.swiglu_branch(x)

        # Combine representations
        combined = torch.cat([feat_relu, feat_tanh, feat_sin, feat_swiglu], dim=1)
        return self.classifier(combined)

unified_model = UnifiedMultiActivationModel()
print(f"Unified Model Parameter Count: {sum(p.numel() for p in unified_model.parameters())}")

